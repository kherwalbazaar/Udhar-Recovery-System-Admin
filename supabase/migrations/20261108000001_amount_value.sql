CREATE TABLE IF NOT EXISTS public.amount_value (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  amount numeric(12, 2) NOT NULL
);

ALTER TABLE public.amount_value
  ADD COLUMN IF NOT EXISTS amount numeric(12, 2);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.amount_value'::regclass
      AND conname = 'amount_value_amount_positive'
  ) THEN
    ALTER TABLE public.amount_value
      ADD CONSTRAINT amount_value_amount_positive
      CHECK (amount IS NOT NULL AND amount > 0) NOT VALID;
  END IF;
END
$$;

ALTER TABLE public.amount_value ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.amount_value TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.is_latest_amount_value(row_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.amount_value
    WHERE id = row_id
      AND id = (SELECT max(id) FROM public.amount_value)
  );
$$;

REVOKE ALL ON FUNCTION public.is_latest_amount_value(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_latest_amount_value(bigint) TO anon, authenticated;

DROP POLICY IF EXISTS "Public can read amount values" ON public.amount_value;
DROP POLICY IF EXISTS "Public can read latest amount value" ON public.amount_value;
CREATE POLICY "Public can read latest amount value"
  ON public.amount_value
  FOR SELECT
  TO anon, authenticated
  USING (public.is_latest_amount_value(id));

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'amount_value'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.amount_value;
  END IF;
END
$$;
